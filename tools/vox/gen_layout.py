#!/usr/bin/env python3
"""gen_layout.py [--md]: the per-mode field layout of an OpenVoxNB block.

Writes firmware/components/oc_vox/oc_vox_layout.c (run from anywhere), or
with --md prints the layout tables for docs/openvox/BITSTREAM.md. The
schedule below is the normative description of the bitstream (PLAN.md
§1.3): which parameter is sent on which frame with how many bits, in
priority order. The bit string a block carries is these fields written
MSB-first in this order; its first 12 x golay bits are class A, the next
8 x hamming bits class B, the rest class C (oc_vox_fec.h).
"""
import os
import sys

ODD, EVEN, ALL = (1, 3, 5), (0, 2, 4), (0, 1, 2, 3, 4, 5)

# mode: E (frames, abs bits, delta bits), EMID (3 bits on every frame),
# P (frames, abs bits, delta bits), V (list of (frames, kind)), VMIX {frame: bits},
# S1 frames (10 bits each), S2/S3/S4 {frame: bits}, golay words, hamming words,
# crc bits, interleaver width.
SPEC = {
    600:  dict(E=(ODD, 6, 2), P=(ODD, 7, 3), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={}, S3={}, S4={},
               EMID=False, G=1, H=0, CRC=0, W=24),
    800:  dict(E=(ODD, 6, 3), P=(ODD, 7, 4), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={1: 6, 5: 6}, S3={}, S4={},
               EMID=False, G=1, H=2, CRC=0, W=24),
    1000: dict(E=(ALL, 6, 3), P=(ALL, 7, 3), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={1: 6, 3: 4, 5: 6}, S3={},
               S4={}, EMID=False, G=1, H=3, CRC=0, W=24),
    1200: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk")], VMIX={1: 2}, S1=ODD, S2={1: 6, 3: 7, 5: 6},
               S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1400: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk"), (EVEN, "cls")], VMIX={}, S1=ALL,
               S2={1: 3, 3: 3, 5: 3}, S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1600: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk"), (EVEN, "cls")], VMIX={}, S1=ALL,
               S2={0: 6, 1: 5, 2: 6, 3: 5, 4: 6, 5: 5}, S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1800: dict(E=(ALL, 6, 4), P=(ALL, 7, 4), V=[(ALL, "msk")], VMIX={1: 2, 3: 2, 5: 2}, S1=ALL,
               S2={f: 6 for f in ALL}, S3={}, S4={}, EMID=False, G=2, H=3, CRC=0, W=24),
    2400: dict(E=(ALL, 6, 4), P=(ALL, 7, 5), V=[(ALL, "msk")], VMIX={f: 2 for f in ALL}, S1=ALL,
               S2={f: 8 for f in ALL}, S3={0: 6, 1: 5, 2: 6, 3: 5, 4: 6, 5: 5}, S4={}, EMID=False,
               G=3, H=2, CRC=8, W=24),
    3200: dict(E=(ALL, 7, 4), P=(ALL, 8, 5), V=[(ALL, "msk")], VMIX={0: 3, 1: 2, 2: 2, 3: 2, 4: 2, 5: 2},
               S1=ALL, S2={f: 8 for f in ALL}, S3={f: 8 for f in ALL}, S4={f: 8 for f in ALL}, EMID=True,
               G=3, H=4, CRC=12, W=24),
}
MODES = list(SPEC)
KINDS = ["T", "E_ABS", "E_DEL", "E_MID", "P_ABS", "P_DEL", "V_CLS", "V_MSK", "V_MIX", "S1", "S2", "S3", "S4"]


def fields(bps):
    """The priority-ordered (kind, frame, bits) list of a mode."""
    s = SPEC[bps]
    ef, eabs, edel = s["E"]
    pf, pabs, pdel = s["P"]
    vmask = [(f, 4) for fr, k in s["V"] if k == "msk" for f in fr]
    vcls = [(f, 2) for fr, k in s["V"] if k == "cls" for f in fr]
    first_v = min(vmask) if vmask else min(vcls)
    out = [("T", 0, 1), ("E_ABS", ef[0], eabs)]
    out.append(("V_MSK" if vmask else "V_CLS", first_v[0], first_v[1]))
    out.append(("P_ABS", pf[0], pabs))
    out.append(("S1", s["S1"][0], 10))
    out += [("E_DEL", f, edel) for f in ef[1:]]
    out += [("P_DEL", f, pdel) for f in pf[1:]]
    rest_v = sorted([("V_MSK", f, b) for f, b in vmask] + [("V_CLS", f, b) for f, b in vcls], key=lambda r: r[1])
    out += [r for r in rest_v if (r[1], r[2]) != first_v or r[0] != ("V_MSK" if vmask else "V_CLS")]
    out += [("V_MIX", f, b) for f, b in sorted(s["VMIX"].items())]
    out += [("S1", f, 10) for f in s["S1"][1:]]
    out += [("S2", f, b) for f, b in sorted(s["S2"].items())]
    out += [("S3", f, b) for f, b in sorted(s["S3"].items())]
    if s["EMID"]:
        out += [("E_MID", f, 3) for f in ALL]
    out += [("S4", f, b) for f, b in sorted(s["S4"].items())]
    return out


def check():
    for bps in MODES:
        s = SPEC[bps]
        block = bps * 120 // 1000
        params = sum(b for _, _, b in fields(bps))
        fec = 12 * s["G"] + 4 * s["H"] + s["CRC"]
        assert params + fec == block, (bps, params, fec, block)
        assert block % s["W"] == 0, (bps, block, s["W"])
        assert params >= 12 * s["G"] + 8 * s["H"]
        assert len(fields(bps)) <= 64


def c_source():
    lines = ["/* Generated by tools/vox/gen_layout.py from its SPEC: do not edit, re-run the",
             " * script. The field order is the bit order of the block's parameter string;",
             " * its prefixes are the FEC classes (oc_vox_fec.h). */",
             '#include "oc_vox_layout.h"', ""]
    for bps in MODES:
        lines.append(f"static const oc_vox_field_t F_{bps}[] = {{")
        row = []
        for k, f, b in fields(bps):
            row.append(f"{{ OC_VOX_F_{k}, {f}, {b} }}")
            if len(row) == 4:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const oc_vox_shape_t SHAPES[OC_VOX_MODE_COUNT] = {")
    for bps in MODES:
        s = SPEC[bps]
        n = len(fields(bps))
        params = sum(b for _, _, b in fields(bps))
        lines.append(f"    {{ F_{bps}, {n}, {params}, {s['G']}, {s['H']}, {s['CRC']}, {s['W']}, {bps * 120 // 8000} }},")
    lines.append("};")
    lines.append("")
    lines.append("const oc_vox_shape_t *oc_vox_shape(oc_vox_mode_t m)")
    lines.append("{")
    lines.append("    return ((int)m >= 0 && (int)m < (int)OC_VOX_MODE_COUNT) ? &SHAPES[m] : (const oc_vox_shape_t *)0;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def markdown():
    out = []
    for bps in MODES:
        s = SPEC[bps]
        block = bps * 120 // 1000
        a, b = 12 * s["G"], 8 * s["H"]
        out.append(f"### OVX-{bps}: {block} bits ({block // 8} bytes), {s['G']} Golay, {s['H']} Hamming, CRC-{s['CRC'] or 'none'}, interleaver width {s['W']}\n")
        out.append("| # | Field | Frame | Bits | Position | Class |")
        out.append("|--:|---|--:|--:|---|---|")
        pos = 0
        for i, (k, f, bits) in enumerate(fields(bps)):
            end = pos + bits
            cls = "A" if end <= a else "B" if pos >= a and end <= a + b else "C" if pos >= a + b else \
                ("A/B" if pos < a < end <= a + b else "B/C" if a <= pos < a + b < end else "A/C" if b == 0 else "A/B/C")
            out.append(f"| {i} | {k} | {f} | {bits} | {pos}-{end - 1} | {cls} |")
            pos = end
        out.append("")
    return "\n".join(out)


def golden(bps, values):
    """The parameter string for field values (for the tests), as bytes."""
    bits = []
    for (k, f, b), v in zip(fields(bps), values):
        bits += [(v >> (b - 1 - i)) & 1 for i in range(b)]
    while len(bits) % 8:
        bits.append(0)
    return bytes(sum(bit << (7 - i) for i, bit in enumerate(bits[j:j + 8])) for j in range(0, len(bits), 8))


if __name__ == "__main__":
    check()
    if "--md" in sys.argv:
        print(markdown())
    elif "--golden" in sys.argv:
        for bps in MODES:
            vals = [((i * 7 + 3) & ((1 << b) - 1)) for i, (_, _, b) in enumerate(fields(bps))]
            print(bps, len(fields(bps)), golden(bps, vals).hex())
    else:
        root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        path = os.path.join(root, "firmware", "components", "oc_vox", "oc_vox_layout.c")
        with open(path, "w") as fh:
            fh.write(c_source())
        print("wrote", path)
