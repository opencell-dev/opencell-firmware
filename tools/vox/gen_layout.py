#!/usr/bin/env python3
"""gen_layout.py [--md]: the per-mode field layout of an OpenVoxNB block.

Writes firmware/components/oc_vox/oc_vox_layout.c (run from anywhere), or
with --md prints the layout tables for docs/openvox/BITSTREAM.md. The
schedule below is the normative description of the bitstream (PLAN.md
§1.3): which parameter is sent on which frame with how many bits, in
priority order. The bit string a block carries is these fields written
MSB-first in this order; its first 12 x golay bits are class A, the next
8 x hamming bits class B, the rest class C (oc_vox_fec.h).
"""
import os
import sys

ODD, EVEN, ALL = (1, 3, 5), (0, 2, 4), (0, 1, 2, 3, 4, 5)

# mode: E (frames, abs bits, delta bits), EMID (3 bits on every frame),
# P (frames, abs bits, delta bits), V (list of (frames, kind)), VMIX {frame: bits},
# S1 frames (10 bits each), S2/S3/S4 {frame: bits}, golay words, hamming words,
# crc bits, interleaver width.
SPEC = {
    600:  dict(E=(ODD, 6, 2), P=(ODD, 7, 3), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={}, S3={}, S4={},
               EMID=False, G=1, H=0, CRC=0, W=24),
    800:  dict(E=(ODD, 6, 3), P=(ODD, 7, 4), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={1: 6, 5: 6}, S3={}, S4={},
               EMID=False, G=1, H=2, CRC=0, W=24),
    1000: dict(E=(ALL, 6, 3), P=(ALL, 7, 3), V=[(ODD, "cls")], VMIX={}, S1=ODD, S2={1: 6, 3: 4, 5: 6}, S3={},
               S4={}, EMID=False, G=1, H=3, CRC=0, W=24),
    1200: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk")], VMIX={1: 2}, S1=ODD, S2={1: 6, 3: 7, 5: 6},
               S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1400: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk"), (EVEN, "cls")], VMIX={}, S1=ALL,
               S2={1: 3, 3: 3, 5: 3}, S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1600: dict(E=(ALL, 6, 3), P=(ALL, 7, 4), V=[(ODD, "msk"), (EVEN, "cls")], VMIX={}, S1=ALL,
               S2={0: 6, 1: 5, 2: 6, 3: 5, 4: 6, 5: 5}, S3={}, S4={}, EMID=False, G=2, H=2, CRC=0, W=24),
    1800: dict(E=(ALL, 6, 4), P=(ALL, 7, 4), V=[(ALL, "msk")], VMIX={1: 2, 3: 2, 5: 2}, S1=ALL,
               S2={f: 6 for f in ALL}, S3={}, S4={}, EMID=False, G=2, H=3, CRC=0, W=24),
    2400: dict(E=(ALL, 6, 4), P=(ALL, 7, 5), V=[(ALL, "msk")], VMIX={f: 2 for f in ALL}, S1=ALL,
               S2={f: 8 for f in ALL}, S3={0: 6, 1: 5, 2: 6, 3: 5, 4: 6, 5: 5}, S4={}, EMID=False,
               G=3, H=2, CRC=8, W=24),
    3200: dict(E=(ALL, 7, 4), P=(ALL, 8, 5), V=[(ALL, "msk")], VMIX={0: 3, 1: 2, 2: 2, 3: 2, 4: 2, 5: 2},
               S1=ALL, S2={f: 8 for f in ALL}, S3={f: 8 for f in ALL}, S4={f: 8 for f in ALL}, EMID=True,
               G=3, H=4, CRC=12, W=24),
}
MODES = list(SPEC)
KINDS = ["T", "E_ABS", "E_DEL", "E_MID", "P_ABS", "P_DEL", "V_CLS", "V_MSK", "V_MIX", "S1", "S2", "S3", "S4"]


def fields(bps):
    """The priority-ordered (kind, frame, bits) list of a mode."""
    s = SPEC[bps]
    ef, eabs, edel = s["E"]
    pf, pabs, pdel = s["P"]
    vmask = [(f, 4) for fr, k in s["V"] if k == "msk" for f in fr]
    vcls = [(f, 2) for fr, k in s["V"] if k == "cls" for f in fr]
    first_v = min(vmask) if vmask else min(vcls)
    out = [("T", 0, 1), ("E_ABS", ef[0], eabs)]
    out.append(("V_MSK" if vmask else "V_CLS", first_v[0], first_v[1]))
    out.append(("P_ABS", pf[0], pabs))
    out.append(("S1", s["S1"][0], 10))
    out += [("E_DEL", f, edel) for f in ef[1:]]
    out += [("P_DEL", f, pdel) for f in pf[1:]]
    rest_v = sorted([("V_MSK", f, b) for f, b in vmask] + [("V_CLS", f, b) for f, b in vcls], key=lambda r: r[1])
    out += [r for r in rest_v if (r[1], r[2]) != first_v or r[0] != ("V_MSK" if vmask else "V_CLS")]
    out += [("V_MIX", f, b) for f, b in sorted(s["VMIX"].items())]
    out += [("S1", f, 10) for f in s["S1"][1:]]
    out += [("S2", f, b) for f, b in sorted(s["S2"].items())]
    out += [("S3", f, b) for f, b in sorted(s["S3"].items())]
    if s["EMID"]:
        out += [("E_MID", f, 3) for f in ALL]
    out += [("S4", f, b) for f, b in sorted(s["S4"].items())]
    return out


def check():
    for bps in MODES:
        s = SPEC[bps]
        block = bps * 120 // 1000
        params = sum(b for _, _, b in fields(bps))
        fec = 12 * s["G"] + 4 * s["H"] + s["CRC"]
        assert params + fec == block, (bps, params, fec, block)
        assert block % s["W"] == 0, (bps, block, s["W"])
        assert params >= 12 * s["G"] + 8 * s["H"]
        assert len(fields(bps)) <= 64


def c_source():
    lines = ["/* Generated by tools/vox/gen_layout.py from its SPEC: do not edit, re-run the",
             " * script. The field order is the bit order of the block's parameter string;",
             " * its prefixes are the FEC classes (oc_vox_fec.h). */",
             '#include "oc_vox_layout.h"', ""]
    for bps in MODES:
        lines.append(f"static const oc_vox_field_t F_{bps}[] = {{")
        row = []
        for k, f, b in fields(bps):
            row.append(f"{{ OC_VOX_F_{k}, {f}, {b} }}")
            if len(row) == 4:
                lines.append("    " + ", ".join(row) + ",")
                row = []
        if row:
            lines.append("    " + ", ".join(row) + ",")
        lines.append("};")
    lines.append("")
    lines.append("static const oc_vox_shape_t SHAPES[OC_VOX_MODE_COUNT] = {")
    for bps in MODES:
        s = SPEC[bps]
        n = len(fields(bps))
        params = sum(b for _, _, b in fields(bps))
        lines.append(f"    {{ F_{bps}, {n}, {params}, {s['G']}, {s['H']}, {s['CRC']}, {s['W']}, {bps * 120 // 8000} }},")
    lines.append("};")
    lines.append("")
    lines.append("const oc_vox_shape_t *oc_vox_shape(oc_vox_mode_t m)")
    lines.append("{")
    lines.append("    return ((int)m >= 0 && (int)m < (int)OC_VOX_MODE_COUNT) ? &SHAPES[m] : (const oc_vox_shape_t *)0;")
    lines.append("}")
    return "\n".join(lines) + "\n"


PROSE = """# OpenVoxNB bitstream (version 0)

The normative description of what an OpenVoxNB block carries. Generated by
`tools/vox/gen_layout.py --md` from the same schedule that generates
`oc_vox_layout.c`: do not edit, change the schedule and re-run. Read with
`PLAN.md` §1 (what the parameters mean) and `INTEGRATION.md` (where blocks
travel). `OC_VOX_VERSION` is 0: the layout may still change before the
Task 13 freeze, which makes it 1.

## The block

- Audio: 8 kHz mono 16-bit, analysed in 20 ms frames of 160 samples. A
  **block** is six frames, 120 ms, the OpenCell radio frame. The coded block
  covers the input delayed by 80 samples (the analysis lookahead), a constant
  offset the decoder's output keeps.
- Nine modes; a block is bit/s x 0.12 bits, a whole number of bytes, and no
  two modes share a size, so a transport that keeps payload lengths implies
  the mode: 9, 12, 15, 18, 21, 24, 27, 36, 48 bytes for 600, 800, 1000, 1200,
  1400, 1600, 1800, 2400, 3200 bit/s.
- On OpenCell links a block is the whole app data frame, headerless; the
  call's codec byte (ids 3-6, `oc_vox_modes.h`) fixed the mode. In `.ovx`
  files (tools only) a two-byte header, the magic `0xC5` then
  `version << 4 | mode`, precedes headerless blocks.

## Parameters (per 20 ms frame; `oc_vox_int.h`)

| Symbol | Meaning | Domain |
|---|---|---|
| `e` | frame energy (RMS against 32768) | 0.75 dB steps, 0 = -96 dBFS (and silence) ... 127 = -0.75 dBFS |
| `p` | pitch | `f0 = 50 Hz x 2^(p/84)`, 0..255 = 50..410 Hz |
| `v` | voicing | bit b: band b voiced; bands 0-600, 600-1200, 1200-2400, 2400-4000 Hz |
| `vmix` | aperiodicity of the voiced bands | 0 periodic .. 7 dispersed |
| `emid` | energy of the second half-frame minus the first | 0.75 dB steps (OVX-3200 only) |
| `s[0..11]` | log power density per band minus the frame's mean over bands | 0.75 dB steps; band edges 100, 300, 500, 700, 900, 1150, 1450, 1800, 2200, 2650, 3150, 3700, 4000 Hz |

## Fields

Every field is written MSB-first, in the order of the tables below, into
the block's **parameter string**. Field kinds:

- `T`: the toggle, alternating every block (a repeat tells a receiver without sequence numbers that a block went missing).
- `E_ABS` (6 or 7 bits): `e >> (7 - bits)`; reconstructed at the centre of its step, 0 staying 0. `E_DEL` (2, 3, 4 bits): an index into the delta table of that width against the previous transmitted frame's reconstruction (`oc_vox_quant.c`: 2 bits {-8, -2, 0, +6}, 3 bits {-16, -8, -4, -2, 0, +4, +8, +16}, 4 bits {-24 .. +24}, in 0.75 dB). `E_MID` (3 bits): {-16, -8, -4, 0, +4, +8, +16, +32}.
- `P_ABS` (7 or 8 bits): `p >> (8 - bits)`; `P_DEL` (3, 4, 5 bits): delta tables in 1/84 octave (3 bits {-42, -14, -4, 0, +4, +14, +42, +84}; 4 and 5 bits wider and finer; an octave is one step away in each).
- `V_CLS` (2 bits): 0 unvoiced, 1 band 0, 2 bands 0-1, 3 all bands. `V_MSK` (4 bits): the mask itself. `V_MIX` (2 or 3 bits): `vmix >> (3 - bits)`.
- `S1` (10 bits): the envelope's 12-point DCT coefficients c1..c4 as 3, 3, 2, 2-bit uniform quantizers (mid-rise at 1-2 bits, mid-tread above; base steps 128, 192, 96, 48 at 2 bits, halving per extra bit). `S2` (3-8 bits): c5..c7; `S3` (5-8 bits): c8..c11; `S4` (8 bits): a quarter-step sign correction of c1..c8. The sub-field widths per total width are in `oc_vox_quant.c` (`s2_subs`, `s3_subs`).
- Frames a mode does not transmit a parameter on are interpolated by the decoder: `e`, `p` and `s` linearly between the transmitted neighbours (the previous block's last frame standing in before the first), `v` from the next transmitted frame, `vmix` held, `emid` zero.

## Protection

The parameter string's first `12 x golay` bits are **class A**, each 12 coded
as an extended Golay(24,12) word (generator x^11+x^10+x^6+x^5+x^4+x^2+1 in
systematic form, data then 11 check bits then overall parity; corrects 3
errors, detects 4); the next `8 x hamming` bits are **class B**, each 8 coded
as a Hamming(12,8) word (parity-check columns 3, 5, 6, 7, 9, 10, 11, 12 for
the data bits, 8, 4, 2, 1 for the parity bits; corrects 1); the rest is
**class C**, sent as is; then, in OVX-2400 and OVX-3200, a CRC (8 bits,
polynomial 0x2F; 12 bits, 0x80F; init 0, MSB-first) over the class B and C
bits. The coded block, in that order, is written row by row into a matrix
24 bits wide and read column by column: a Golay word is one row, so any
burst of up to 3 x (block bits / 24) consecutive block bits is corrected
in full.

Decoder policy: a Golay word that fails makes the block lost (concealed,
`PLAN.md` §1.4); a failed CRC drops the S3, S4 and E_MID fields; a Hamming
word's correction is taken as is.

## Layout per mode

Position is the bit offset in the parameter string; class is where the
field's bits land (a field straddling a boundary has its MSBs in the
better-protected class).

"""


def markdown():
    out = [PROSE]
    for bps in MODES:
        s = SPEC[bps]
        block = bps * 120 // 1000
        a, b = 12 * s["G"], 8 * s["H"]
        out.append(f"### OVX-{bps}: {block} bits ({block // 8} bytes), {s['G']} Golay, {s['H']} Hamming, CRC-{s['CRC'] or 'none'}, interleaver width {s['W']}\n")
        out.append("| # | Field | Frame | Bits | Position | Class |")
        out.append("|--:|---|--:|--:|---|---|")
        pos = 0
        for i, (k, f, bits) in enumerate(fields(bps)):
            end = pos + bits
            cls = "A" if end <= a else "B" if pos >= a and end <= a + b else "C" if pos >= a + b else \
                ("A/B" if pos < a < end <= a + b else "B/C" if a <= pos < a + b < end else "A/C" if b == 0 else "A/B/C")
            out.append(f"| {i} | {k} | {f} | {bits} | {pos}-{end - 1} | {cls} |")
            pos = end
        out.append("")
    return "\n".join(out)


def golden(bps, values):
    """The parameter string for field values (for the tests), as bytes."""
    bits = []
    for (k, f, b), v in zip(fields(bps), values):
        bits += [(v >> (b - 1 - i)) & 1 for i in range(b)]
    while len(bits) % 8:
        bits.append(0)
    return bytes(sum(bit << (7 - i) for i, bit in enumerate(bits[j:j + 8])) for j in range(0, len(bits), 8))


if __name__ == "__main__":
    check()
    if "--md" in sys.argv:
        root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        path = os.path.join(root, "docs", "openvox", "BITSTREAM.md")
        with open(path, "w") as fh:
            fh.write(markdown())
        print("wrote", path)
    elif "--golden" in sys.argv:
        for bps in MODES:
            vals = [((i * 7 + 3) & ((1 << b) - 1)) for i, (_, _, b) in enumerate(fields(bps))]
            print(bps, len(fields(bps)), golden(bps, vals).hex())
    else:
        root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        path = os.path.join(root, "firmware", "components", "oc_vox", "oc_vox_layout.c")
        with open(path, "w") as fh:
            fh.write(c_source())
        print("wrote", path)
