#!/usr/bin/env python3
"""gen_fx_tables.py: the tables of oc_vox's fixed-point kernels (fx/oc_vox_fx_tables.c)."""
import math
import os

hann = [round(32767 * (0.5 - 0.5 * math.cos(2 * math.pi * (i + 0.5) / 256))) for i in range(256)]
sin1024 = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
tw = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
log2m = [round(256 * math.log2(1 + i / 64)) for i in range(65)]
exp2f = [round(32768 * 2 ** (i / 64)) for i in range(65)]


def fmt(name, typ, vals, per=16):
    out = [f"{typ} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


src = ["/* Tables of the fixed-point kernels, generated by tools/vox/gen_fx_tables.py:",
       " * do not edit, re-run the script. */",
       '#include "oc_vox_fx_int.h"', "",
       fmt("oc_vox_fx_hann256", "const int16_t", hann),
       fmt("oc_vox_fx_sin1024", "const int16_t", sin1024),
       fmt("oc_vox_fx_tw256", "const int16_t", tw),
       fmt("oc_vox_fx_log2m65", "const uint16_t", log2m),
       fmt("oc_vox_fx_exp2f65", "const uint32_t", exp2f), ""]
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
path = os.path.join(root, "firmware", "components", "oc_vox", "fx", "oc_vox_fx_tables.c")
open(path, "w").write("\n".join(src))
print("wrote", path)
